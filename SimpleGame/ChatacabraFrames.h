inline int Direction(float x, float z)
{
    constexpr float step=3.14159265358979323846f/4;
    const float screenX=x-z, screenY=(x+z)*.5f;
    if (screenX==0 && screenY==0) return 0;
    const float angle=std::atan2(-screenX,-screenY);
    return (static_cast<int>(std::floor(angle/step+.5f))+8)%8;
}
